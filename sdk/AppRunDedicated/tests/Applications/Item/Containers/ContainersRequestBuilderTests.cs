    {
        var requestAdapter = Substitute.For<IRequestAdapter>();
        requestAdapter.BaseUrl = "https://api.example.com";
        var pathParameters = new Dictionary<string, object>
        {
            { "baseurl", "https://api.example.com" },
            { "applicationID", _validApplicationID }
        };
        var builder = new ContainersRequestBuilder(pathParameters, requestAdapter, _mockLoggerFactory);
        var newUrl = "https://api.example.com/applications/12345678-1234-1234-1234-123456789012/containers";

        var newBuilder = builder.WithUrl(newUrl);

        Assert.NotNull(newBuilder);
        Assert.IsType<ContainersRequestBuilder>(newBuilder);
        Assert.NotSame(builder, newBuilder);
    }
